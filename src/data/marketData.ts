// Helper to generate historical price points
function generateHistory(basePrice: number, volatility: number, trend: 'up' | 'down' | 'flat'): Record<'1D' | '1W' | '1M' | '3M' | '1Y' | 'ALL', PricePoint[]> {
  const generateSeries = (count: number, variance: number, periodLabel: (i: number) => string): PricePoint[] => {
    const points: PricePoint[] = [];
    let current = basePrice * (trend === 'up' ? 0.92 : trend === 'down' ? 1.08 : 0.98);
    for (let i = 0; i < count; i++) {
      const delta = (Math.random() - 0.48) * variance * current;
      current = Math.max(0.01, current + delta);
      const open = current - (Math.random() - 0.5) * variance * current * 0.5;
      const high = Math.max(current, open) + Math.random() * variance * current * 0.3;
      const low = Math.min(current, open) - Math.random() * variance * current * 0.3;
      const close = current;
      const volume = Math.floor(Math.random() * 5000000 + 1000000);
      
      points.push({
        time: periodLabel(i),
        price: parseFloat(close.toFixed(2)),
        open: parseFloat(open.toFixed(2)),
        high: parseFloat(high.toFixed(2)),
        low: parseFloat(low.toFixed(2)),
        close: parseFloat(close.toFixed(2)),
        volume,
        ma20: parseFloat((close * (0.99 + Math.random() * 0.02)).toFixed(2)),
        ma50: parseFloat((close * (0.98 + Math.random() * 0.03)).toFixed(2)),
        rsi: Math.floor(35 + Math.random() * 40),
      });
    }
    // Ensure final point matches basePrice approximately
    points[points.length - 1].price = basePrice;
    points[points.length - 1].close = basePrice;
    return points;
  };

  return {
    '1D': generateSeries(24, 0.003, (i) => `${i.toString().padStart(2, '0')}:00`),
    '1W': generateSeries(7, 0.012, (i) => ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'][i]),
    '1M': generateSeries(30, 0.018, (i) => `Day ${i + 1}`),
    '3M': generateSeries(12, 0.025, (i) => `Wk ${i + 1}`),
    '1Y': generateSeries(12, 0.04, (i) => ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'][i]),
    'ALL': generateSeries(20, 0.06, (i) => `${2006 + i}`),
  };
}

